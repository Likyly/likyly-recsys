// `npx @likyly/wizard pixel`: the purchases of a Shopify theme. The checkout is Shopify's own page,
// where no theme code runs: only a pixel (Shopify admin → Settings → Customer events) sees the
// add to cart and the order. This prints that pixel, ready to paste, with the theme's public key.
//
// Attribution: a click in a LIKYLY block keeps [recommendationId, placement, time] per product in
// localStorage (likyly_rec, written by sections/likyly-recommendations.liquid, the same format as
// the LIKYLY Shopify app); the pixel reads it when that product is added to the cart or bought,
// so the purchase carries the recommendation_id - what LIKYLY's revenue counts. Same browser and
// same domain only: a click on 127.0.0.1 (shopify theme dev) is not seen by the checkout on
// <store>.myshopify.com - test through the store's own address (the preview link).

import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { API_URL } from "./verify.mjs";
import { themeStore } from "./preview.mjs";

const KEY_FILE = "snippets/likyly-key.liquid";

/** The public key the theme already uses, or null. */
export function themePublicKey(dir) {
  const file = join(dir, KEY_FILE);
  if (!existsSync(file)) return null;
  return readFileSync(file, "utf8").match(/pk_[A-Za-z0-9_-]+/)?.[0] ?? null;
}

/** The custom pixel's code: plain JS for Shopify's sandbox (analytics, browser, init are given). */
export function shopifyCustomPixel(key, apiUrl = API_URL) {
  return `// LIKYLY - add to cart and purchases, so LIKYLY can count the revenue its recommendations bring.
// Generated by @likyly/wizard (npx @likyly/wizard pixel). Shopify admin → Settings → Customer events
// → Add custom pixel → paste this code → Save → Connect.
const LIKYLY_KEY = ${JSON.stringify(key)};
const LIKYLY_API = ${JSON.stringify(apiUrl)};

const numericId = (value) => (String(value ?? "").match(/(\\d+)$/) || [])[1] || null;

async function stored(name) {
  try {
    return await browser.localStorage.getItem(name);
  } catch (error) {
    return null;
  }
}

// The visitor: the same anonymous id as the LIKYLY blocks, and the customer when signed in.
async function who(orderId) {
  const out = {};
  const session = await stored("likyly_anonymous_id");
  if (session) out.session_id = session;
  const customer = numericId(init && init.data && init.data.customer && init.data.customer.id);
  if (customer) out.user_id = customer;
  if (!out.session_id && !out.user_id && orderId) out.session_id = "shopify_order_" + orderId;
  return out;
}

// The recommendation this product was clicked in (30 days at most), from the LIKYLY block.
async function attribution(productId) {
  try {
    const entry = JSON.parse((await stored("likyly_rec")) || "{}")[productId];
    if (Array.isArray(entry) && entry[0] && Date.now() - Number(entry[2] || 0) < 30 * 24 * 3600 * 1000) {
      return entry[1] ? { recommendation_id: String(entry[0]), placement: String(entry[1]) } : { recommendation_id: String(entry[0]) };
    }
  } catch (error) {}
  return {};
}

function send(events) {
  if (!events.length) return;
  fetch(LIKYLY_API + "/events/batch", {
    method: "POST",
    headers: { "Content-Type": "application/json", "X-API-Key": LIKYLY_KEY, "X-Likyly-Client": "likyly-wizard shopify-custom-pixel" },
    body: JSON.stringify({ events: events }),
    keepalive: true,
  }).catch(() => {});
}

analytics.subscribe("product_added_to_cart", async (event) => {
  const line = event.data && event.data.cartLine;
  const productId = numericId(line && line.merchandise && line.merchandise.product && line.merchandise.product.id);
  if (!productId) return;
  const price = Number(line.merchandise.price && line.merchandise.price.amount);
  send([Object.assign({
    event_type: "add_to_cart",
    item_id: productId,
    quantity: Math.max(1, Number(line.quantity) || 1),
    event_id: "cart_" + event.id,
    occurred_at: event.timestamp,
  }, await who(), await attribution(productId), Number.isFinite(price) ? { properties: { price: price, currency: line.merchandise.price.currencyCode } } : {})]);
});

// One purchase per product of the order, with its price: what LIKYLY's revenue adds up.
analytics.subscribe("checkout_completed", async (event) => {
  const checkout = event.data && event.data.checkout;
  if (!checkout) return;
  const orderId = numericId(checkout.order && checkout.order.id) || String(checkout.token || event.id);
  const byProduct = {};
  for (const line of checkout.lineItems || []) {
    const productId = numericId(line.variant && line.variant.product && line.variant.product.id);
    if (!productId) continue;
    const quantity = Math.max(1, Number(line.quantity) || 1);
    const total = Number(line.finalLinePrice ? line.finalLinePrice.amount : Number(line.variant.price.amount) * quantity);
    const sum = byProduct[productId] || { quantity: 0, revenue: 0 };
    sum.quantity += quantity;
    sum.revenue += Number.isFinite(total) ? total : 0;
    byProduct[productId] = sum;
  }
  const buyer = await who(orderId);
  const events = [];
  for (const productId of Object.keys(byProduct)) {
    const sum = byProduct[productId];
    events.push(Object.assign({
      event_type: "purchase",
      item_id: productId,
      quantity: sum.quantity,
      // The same order seen twice (thank-you page reloaded) counts once.
      event_id: "purchase_" + orderId + "_" + productId,
      occurred_at: event.timestamp,
      properties: {
        order_id: orderId,
        price: Math.round((sum.revenue / sum.quantity) * 100) / 100,
        revenue: Math.round(sum.revenue * 100) / 100,
        currency: checkout.currencyCode,
      },
    }, buyer, await attribution(productId)));
  }
  send(events);
});
`;
}

/** Where the pixel is pasted, for this store (or the generic path). */
export function customerEventsUrl(store) {
  const handle = store?.replace(/\.myshopify\.com$/, "");
  return handle ? `https://admin.shopify.com/store/${handle}/settings/customer_events` : "Shopify admin → Settings → Customer events";
}

/** { ok: true, code, url } or { ok: false, text, hint }. */
export async function pixelFor(dir, options = {}) {
  const key = themePublicKey(dir);
  if (!key) return { ok: false, text: `No public key in ${KEY_FILE}: this folder is not a Shopify theme set up by LIKYLY.`, hint: "Run npx @likyly/wizard in the theme folder first." };
  const store = await themeStore(dir, options).catch(() => null);
  return { ok: true, code: shopifyCustomPixel(key), url: customerEventsUrl(store), store };
}
