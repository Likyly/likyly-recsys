/**
 * A Shopify theme has no env file: the public key lives alone in a snippet the section renders
 * (`{% render 'likyly-key' %}`). Rewritten when the key changes. Returns { path, status }.
 */
export function writeKeyFile(dir, file, key, { dryRun = false } = {}) {
  const path = join(dir, file);
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  const previous = current?.match(/pk_[A-Za-z0-9_-]+/)?.[0];
  if (previous === key) return { path, status: "same" };
  if (!dryRun) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, `{%- comment -%} LIKYLY public key, written by @likyly/wizard. Public: safe in the storefront. {%- endcomment -%}${key}\n`);
  }
  return { path, status: current === null ? "added" : "updated" };
}

/** What the wizard writes as the starter file (also used to tell, at uninstall, if it was edited). */
