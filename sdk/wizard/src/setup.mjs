/** Keys that must never reach a browser: secret (`sk_`) and developer (`lk_`) keys. */
export function isServerOnlyKey(key) {
  return /^(sk_|lk_)/.test(key.trim());
}

/**
 * Set `VAR=value` in the env file: appended when absent, replaced in place when it holds another
 * value (a key regenerated on likyly.com invalidates the old one), untouched when identical.
 * Every other line of the file is kept as is. Returns { path, status: "added" | "updated" | "same", previous? }.
 */
export function writeEnv(dir, envFile, envVar, value, { dryRun = false } = {}) {
  const path = join(dir, envFile);
  const current = existsSync(path) ? readFileSync(path, "utf8") : "";
  const line = new RegExp(`^([ \\t]*${envVar}[ \\t]*=[ \\t]*)["']?([^"'\\r\\n]*)["']?[ \\t]*$`, "m");
  const found = current.match(line);
  if (found) {
    const previous = found[2].trim();
    if (previous === value) return { path, status: "same" };
    if (!dryRun) writeFileSync(path, current.replace(line, `${envVar}=${value}`));
    return { path, status: "updated", previous };
  }
  if (!dryRun) {
    const sep = current && !current.endsWith("\n") ? "\n" : "";
    appendFileSync(path, `${sep}# LIKYLY public key (safe in the browser)\n${envVar}=${value}\n`);
  }
  return { path, status: "added" };
}

