/** What the wizard writes as the starter file (also used to tell, at uninstall, if it was edited). */
export function starterContent(starter) {
  return TEMPLATES[starter.template](starter.envExpr);
}

/** Write the framework's starter file, unless a file already exists at that path. */
export function writeStarter(dir, starter, { dryRun = false } = {}) {
  if (!starter) return null;
  const path = join(dir, starter.path);
  if (existsSync(path)) return { path, status: "exists" };
  const content = TEMPLATES[starter.template](starter.envExpr);
  if (!dryRun) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
  return { path, status: "created" };
}

/** The LIKYLY skill, bundled at publish time; falls back to the monorepo copy in development. */
export function readSkill() {
  for (const p of [join(HERE, "..", "skill", "SKILL.md"), join(HERE, "..", "..", "..", "docs", "SKILL.md")]) {
    if (existsSync(p)) return readFileSync(p, "utf8");
  }
  return null;
}

/** Install the skill for Claude Code (`.claude/skills/likyly/SKILL.md`). */
export function writeSkill(dir, { dryRun = false } = {}) {
  const skill = readSkill();
  if (!skill) return null;
  const path = join(dir, ".claude", "skills", "likyly", "SKILL.md");
  const status = existsSync(path) ? "updated" : "created";
  if (!dryRun) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, skill);
  }
  return { path, status };
}

export function commandExists(bin) {
  const probe = process.platform === "win32" ? ["where", [bin]] : ["sh", ["-c", `command -v ${JSON.stringify(bin)}`]];
  return spawnSync(probe[0], probe[1], { stdio: "ignore" }).status === 0;
}

/** Run a command in `dir`, streaming its output. Returns true on success. */
export function run(dir, cmd) {
  const res = spawnSync(cmd[0], cmd.slice(1), { cwd: dir, stdio: "inherit", shell: process.platform === "win32" });
  return res.status === 0;
}

/**
 * Run a command in `dir` without taking over the terminal: each output line goes to `onLine`
 * (the interactive UI shows a live tail). Resolves to true on success.
 */
export function runAsync(dir, cmd, onLine = () => {}) {
  return new Promise((resolveRun) => {
    let child;
    try {
      child = spawn(cmd[0], cmd.slice(1), {
        cwd: dir,
        shell: process.platform === "win32",
        env: { ...process.env, FORCE_COLOR: "0", npm_config_color: "false" },
      });
    } catch {
      resolveRun(false);
      return;
    }
    let buf = "";
    const feed = (chunk) => {
      buf += chunk.toString();
      const lines = buf.split(/\r?\n|\r/);
      buf = lines.pop();
      for (const l of lines) if (l.trim()) onLine(l);
    };
    child.stdout?.on("data", feed);
    child.stderr?.on("data", feed);
    child.on("error", () => resolveRun(false));
    child.on("close", (code) => {
      if (buf.trim()) onLine(buf);
      resolveRun(code === 0);
    });
  });
}

/**
 * Store the developer key for the MCP server in `.likyly/credentials.env`, readable by the
 * owner only. The folder ignores itself (`.likyly/.gitignore` = `*`), so the key can never be
 * committed, whatever the project's own .gitignore says.
 */
export function writeCredentials(dir, developerKey, { dryRun = false, account = null, workspace = null, console: consoleUrl = null } = {}) {
  const folder = join(dir, ".likyly");
  const path = join(folder, "credentials.env");
  if (!dryRun) {
    mkdirSync(folder, { recursive: true });
    writeFileSync(join(folder, ".gitignore"), "# Written by @likyly/wizard: nothing in this folder is ever committed.\n*\n");
    // Which LIKYLY account and workspace the keys belong to: what the console must be signed in
    // with to show this project's catalog (read by the assistant's final report).
    // Console: the LIKYLY site holding this workspace (a local one when testing), for the links.
    const origin = [account && `# Account: ${account}`, workspace && `# Workspace: ${workspace}`, consoleUrl && `# Console: ${consoleUrl}`].filter(Boolean).join("\n");
    writeFileSync(path, `# LIKYLY developer key for the MCP server (never commit it)\n${origin ? `${origin}\n` : ""}LIKYLY_DEVELOPER_KEY=${developerKey}\n`, { mode: 0o600 });
  }
  return { path };
}

/**
 * How the Claude Code commands call the wizard: through npx when it runs from the npm package,
 * or the very file that is running when it was started from a local checkout (not on npm).
 */
export function wizardInvocation(argv1 = process.argv[1]) {
  let bin = argv1 ? resolvePath(argv1) : "";
  try {
    bin = realpathSync(bin);
  } catch {
    // keep the path as given
  }
  if (!bin || /[\\/](_npx|node_modules)[\\/]/.test(bin) || !/likyly-wizard\.mjs$/.test(bin)) return "npx -y @likyly/wizard";
  return `node ${bin.includes(" ") ? JSON.stringify(bin) : bin}`;
}

